export function translate(
  locale: "en" | "fa",
  key: MessageKey,
  values?: Record<string, string>,
) {
  const template = locale === "fa" ? fa[key] : en[key];
  if (!values) return template;
  return template.replace(
    /\{([a-z]+)\}/g,
    (_, token: string) => values[token] ?? "",
  );
}
